// Teksty interfejsu w dwóch językach (NF-C-02). Klucze są wspólne; brakujący klucz w "en"
// zostanie wyświetlony po polsku. Funkcje służą do odmiany przez liczby.

// Polska liczba mnoga: 1 wizyta, 2–4 wizyty, 5+ wizyt (z wyjątkiem 12–14)
function plPlural(n, one, few, many) {
  if (n === 1) return one;
  const last = n % 10;
  const lastTwo = n % 100;
  return last >= 2 && last <= 4 && (lastTwo < 12 || lastTwo > 14) ? few : many;
}

